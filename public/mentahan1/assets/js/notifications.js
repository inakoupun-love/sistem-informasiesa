/**
 * Notification System Handler
 * Manages notification display and updates in the dashboard
 */
class NotificationHandler {
    constructor(config = {}) {
        this.apiBaseUrl = config.apiBaseUrl || '/api/notifications';
        this.refreshInterval = config.refreshInterval || 5000; // 5 seconds
        this.maxNotifications = config.maxNotifications || 10;
        this.container = null;
        this.badge = null;
        this.dropdown = null;
        this.unreadCount = 0;
        this.notifications = [];
        this.autoRefresh = config.autoRefresh !== false;
    }

    /**
     * Initialize notification handler
     */
    init() {
        this.container = document.querySelector('.notification-menu');
        this.badge = document.querySelector('.notification-dot');
        this.dropdown = this.container?.parentElement;

        if (!this.container) {
            console.warn('Notification container not found');
            return;
        }

        this.setupEventListeners();
        this.loadNotifications();

        if (this.autoRefresh) {
            this.startAutoRefresh();
        }
    }

    /**
     * Setup event listeners
     */
    setupEventListeners() {
        // Refresh notifications when dropdown is opened
        if (this.dropdown) {
            this.dropdown.addEventListener('show.bs.dropdown', () => {
                this.loadNotifications();
            });
        }

        // Mark all as read
        const markAllBtn = document.querySelector('[data-mark-all-read]');
        if (markAllBtn) {
            markAllBtn.addEventListener('click', (e) => {
                e.preventDefault();
                this.markAllAsRead();
            });
        }
    }

    /**
     * Load unread notifications
     */
    async loadNotifications() {
        try {
            const response = await fetch(`${this.apiBaseUrl}/unread`);
            const data = await response.json();

            if (data.success) {
                this.notifications = data.notifications;
                this.unreadCount = data.count;
                this.updateUI();
            }
        } catch (error) {
            console.error('Error loading notifications:', error);
        }
    }

    /**
     * Update UI with notifications
     */
    updateUI() {
        // Update badge
        if (this.badge) {
            if (this.unreadCount > 0) {
                this.badge.style.display = 'block';
            } else {
                this.badge.style.display = 'none';
            }
        }

        // Update notification list
        if (this.container) {
            this.renderNotifications();
        }
    }

    /**
     * Render notifications in dropdown
     */
    renderNotifications() {
        const itemsContainer = this.container.querySelector('.notification-items') || this.container;

        // Remove items generated by the previous refresh while keeping the header and controls.
        const items = itemsContainer.querySelectorAll('[data-notification-item]');
        items.forEach(item => item.remove());

        if (this.notifications.length === 0) {
            const emptyItem = document.createElement('div');
            emptyItem.className = 'dropdown-item notification-empty text-center text-muted';
            emptyItem.dataset.notificationItem = 'true';
            emptyItem.innerHTML = '<i class="bi bi-bell-slash me-2" aria-hidden="true"></i><span>Tidak ada notifikasi baru</span>';
            itemsContainer.appendChild(emptyItem);
            return;
        }

        this.notifications.slice(0, this.maxNotifications).forEach(notif => {
            const item = document.createElement('a');
            item.className = `dropdown-item notification-item ${!notif.is_read ? 'unread' : ''}`;
            item.dataset.notificationItem = 'true';
            item.href = notif.action_url || '#';
            if (!notif.action_url) {
                item.style.pointerEvents = 'none';
            }

            item.innerHTML = `
                <div class="notification-item-content">
                    <span class="notification-item-icon"><i class="bi ${notif.icon}" style="color: var(--bs-${notif.color})"></i></span>
                    <div class="notification-item-text">
                        <span class="notification-title">${this.escapeHtml(notif.title)}</span>
                        <span class="notification-message">${this.escapeHtml(notif.message)}</span>
                        <span class="notification-time">${notif.time_ago}</span>
                    </div>
                </div>
            `;

            // Mark as read on click
            item.addEventListener('click', (e) => {
                if (notif.action_url) {
                    e.preventDefault();
                    this.markAsRead(notif.id);
                }
            });

            itemsContainer.appendChild(item);
        });

        // Add footer if there are more notifications
        if (this.notifications.length > this.maxNotifications) {
            const footer = document.createElement('a');
            footer.className = 'dropdown-item text-center text-primary small';
            footer.dataset.notificationItem = 'true';
            footer.href = '#'; // Link to full notification page if exists
            footer.textContent = `Lihat ${this.notifications.length - this.maxNotifications} notifikasi lainnya`;
            itemsContainer.appendChild(footer);
        }
    }

    /**
     * Mark notification as read
     */
    async markAsRead(notificationId) {
        try {
            const response = await fetch(`${this.apiBaseUrl}/${notificationId}/read`, {
                method: 'PUT',
                headers: {
                    'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]')?.content || '',
                    'Content-Type': 'application/json',
                },
            });

            const data = await response.json();

            if (data.success) {
                this.loadNotifications();
            }
        } catch (error) {
            console.error('Error marking notification as read:', error);
        }
    }

    /**
     * Mark all notifications as read
     */
    async markAllAsRead() {
        try {
            const response = await fetch(`${this.apiBaseUrl}/mark-all-as-read`, {
                method: 'PUT',
                headers: {
                    'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]')?.content || '',
                    'Content-Type': 'application/json',
                },
            });

            const data = await response.json();

            if (data.success) {
                this.loadNotifications();
                // Show success message
                this.showToast('Semua notifikasi telah ditandai sebagai telah dibaca', 'success');
            }
        } catch (error) {
            console.error('Error marking all as read:', error);
        }
    }

    /**
     * Delete notification
     */
    async deleteNotification(notificationId) {
        try {
            const response = await fetch(`${this.apiBaseUrl}/${notificationId}`, {
                method: 'DELETE',
                headers: {
                    'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]')?.content || '',
                    'Content-Type': 'application/json',
                },
            });

            const data = await response.json();

            if (data.success) {
                this.loadNotifications();
            }
        } catch (error) {
            console.error('Error deleting notification:', error);
        }
    }

    /**
     * Start auto-refresh
     */
    startAutoRefresh() {
        setInterval(() => {
            this.loadNotifications();
        }, this.refreshInterval);
    }

    /**
     * Stop auto-refresh
     */
    stopAutoRefresh() {
        this.autoRefresh = false;
    }

    /**
     * Show toast notification
     */
    showToast(message, type = 'info') {
        // Create toast element if using Bootstrap
        const toastHtml = `
            <div class="toast align-items-center text-white bg-${type}" role="alert">
                <div class="d-flex">
                    <div class="toast-body">
                        ${this.escapeHtml(message)}
                    </div>
                    <button type="button" class="btn-close btn-close-white me-2 m-auto" data-bs-dismiss="toast"></button>
                </div>
            </div>
        `;

        const container = document.querySelector('.toast-container') || document.body;
        const toastDiv = document.createElement('div');
        toastDiv.innerHTML = toastHtml;
        container.appendChild(toastDiv);

        const toast = new bootstrap.Toast(toastDiv.querySelector('.toast'));
        toast.show();

        toastDiv.addEventListener('hidden.bs.toast', () => {
            toastDiv.remove();
        });
    }

    /**
     * Escape HTML to prevent XSS
     */
    escapeHtml(text) {
        const div = document.createElement('div');
        div.textContent = text;
        return div.innerHTML;
    }

    /**
     * Get unread count
     */
    getUnreadCount() {
        return this.unreadCount;
    }

    /**
     * Get all notifications
     */
    getNotifications() {
        return this.notifications;
    }
}

// Initialize notification handler when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const notificationHandler = new NotificationHandler({
            autoRefresh: true,
            refreshInterval: 5000,
            maxNotifications: 10,
        });
        notificationHandler.init();

        // Store in window for global access
        window.notificationHandler = notificationHandler;
    });
} else {
    const notificationHandler = new NotificationHandler({
        autoRefresh: true,
        refreshInterval: 5000,
        maxNotifications: 10,
    });
    notificationHandler.init();

    // Store in window for global access
    window.notificationHandler = notificationHandler;
}
